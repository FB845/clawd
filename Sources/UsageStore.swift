import Foundation

/// Token counts for one API response, or a sum of them.
struct TokenCounts {
    var input = 0
    var output = 0
    var cacheWrite = 0
    var cacheRead = 0

    /// Tokens Claude actually had to take in or write: everything except context re-read from cache.
    var fresh: Int { input + output + cacheWrite }
    var all: Int { fresh + cacheRead }

    static func + (a: TokenCounts, b: TokenCounts) -> TokenCounts {
        TokenCounts(input: a.input + b.input, output: a.output + b.output,
                    cacheWrite: a.cacheWrite + b.cacheWrite, cacheRead: a.cacheRead + b.cacheRead)
    }

    /// Field-by-field maximum: the same response is logged more than once, sometimes with partial counts.
    func merged(_ b: TokenCounts) -> TokenCounts {
        TokenCounts(input: max(input, b.input), output: max(output, b.output),
                    cacheWrite: max(cacheWrite, b.cacheWrite), cacheRead: max(cacheRead, b.cacheRead))
    }
}

/// What the menu shows: per-day, per-project, and per-model totals.
struct UsageSnapshot {
    struct Day {
        let date: Date
        let tokens: TokenCounts
    }

    var today = TokenCounts()
    var days: [Day] = []                       // oldest first, ending today
    var week = TokenCounts()                   // last 7 days including today
    var month = TokenCounts()                  // last 30 days
    var topProjects: [(name: String, tokens: Int)] = []   // last 7 days, fresh tokens
    var models: [(name: String, share: Double)] = []      // last 7 days, share of fresh tokens
    var oldest: Date?
    var updated = Date.distantPast
    var responses = 0
}

enum UsagePeriod: String, CaseIterable {
    case today, week, month

    var title: String {
        switch self {
        case .today: return "Today"
        case .week: return "7 days"
        case .month: return "30 days"
        }
    }
    /// How many calendar days back the period starts (0 = today only).
    var daysBack: Int {
        switch self {
        case .today: return 0
        case .week: return 6
        case .month: return 29
        }
    }
}

struct ModelUsage: Identifiable {
    let name: String
    let tokens: TokenCounts
    var id: String { name }
}

struct SessionUsage: Identifiable {
    let id: String
    let title: String?
    let first: Date
    let last: Date
    let tokens: TokenCounts
    let responses: Int
    let subagentFresh: Int       // part of `tokens.fresh` that came from subagents
}

struct ProjectUsage: Identifiable {
    let id: String               // log folder name
    let name: String
    let path: String
    let tokens: TokenCounts
    let responses: Int
    let sessions: [SessionUsage]
    let models: [ModelUsage]
}

/// Detailed usage for one period, grouped by project.
struct UsageReport {
    let period: UsagePeriod
    let start: Date
    let total: TokenCounts
    let responses: Int
    let projects: [ProjectUsage]
    let generated: Date
}

/// Reads token usage from Claude Code's local session logs (~/.claude/projects, written by the CLI
/// and the desktop app). Each response is counted once even though the logs repeat it.
/// The log format is internal to Claude Code, so unknown lines are skipped rather than trusted.
final class UsageStore {
    static let shared = UsageStore()

    var onChange: ((UsageSnapshot) -> Void)?
    private(set) var snapshot = UsageSnapshot()

    private struct Record {
        var time: Date
        var folder: String        // the project's folder under ~/.claude/projects
        var session: String
        var sidechain: Bool       // written by a subagent
        var model: String
        var tokens: TokenCounts
    }

    private var folderRoot: [String: String] = [:]          // folder -> shortest working directory seen
    private var customTitles: [String: String] = [:]         // session -> name set by the user
    private var aiTitles: [String: String] = [:]             // session -> name generated by Claude Code

    private let queue = DispatchQueue(label: "clawd.usage", qos: .utility)
    private var records: [String: Record] = [:]          // by response id
    private var offsets: [String: UInt64] = [:]           // bytes already read, per file
    private var timer: DispatchSourceTimer?
    private let root = URL(fileURLWithPath: NSHomeDirectory()).appendingPathComponent(".claude/projects")
    private let iso: ISO8601DateFormatter = {
        let f = ISO8601DateFormatter()
        f.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
        return f
    }()

    func start() {
        guard timer == nil else { return }
        let t = DispatchSource.makeTimerSource(queue: queue)
        t.schedule(deadline: .now(), repeating: 20, leeway: .seconds(5))
        t.setEventHandler { [weak self] in self?.scan() }
        t.resume()
        timer = t
    }

    /// Synchronous scan, for previews and checks.
    func scanNow() -> UsageSnapshot {
        queue.sync { scan() }
        return queue.sync { summarize() }
    }

    func refreshNow() {
        queue.async { [weak self] in self?.scan() }
    }

    // MARK: Scanning

    private func scan() {
        let fm = FileManager.default
        guard let walker = fm.enumerator(at: root, includingPropertiesForKeys: [.fileSizeKey],
                                         options: [.skipsHiddenFiles]) else { return }
        var changed = false
        var seenFiles = Set<String>()
        for case let url as URL in walker where url.pathExtension == "jsonl" {
            autoreleasepool {
                let path = url.path
                seenFiles.insert(path)
                let size = UInt64((try? url.resourceValues(forKeys: [.fileSizeKey]).fileSize) ?? 0)
                var start = offsets[path] ?? 0
                if size < start { start = 0 }        // file was rewritten
                guard size > start else { return }
                let folder = url.pathComponents.dropFirst(root.pathComponents.count).first ?? "Other"
                if let consumed = read(path, folder: folder, from: start) {
                    offsets[path] = start + consumed
                    if consumed > 0 { changed = true }
                }
            }
        }
        offsets = offsets.filter { seenFiles.contains($0.key) }
        if changed || snapshot.updated == .distantPast || !Calendar.current.isDateInToday(snapshot.updated) {
            let snap = summarize()
            DispatchQueue.main.async {
                self.snapshot = snap
                self.onChange?(snap)
            }
        } else {
            DispatchQueue.main.async { self.snapshot.updated = Date() }
        }
    }

    /// Parses complete lines from `start`; returns how many bytes were consumed (a trailing partial
    /// line is left for next time).
    ///
    /// Reads in fixed-size chunks and drains autoreleased objects after each one. Reading whole files
    /// at once kept every log in memory until the scan finished: about 650 MB on first launch.
    private func read(_ path: String, folder: String, from start: UInt64) -> UInt64? {
        guard let h = FileHandle(forReadingAtPath: path) else { return nil }
        defer { try? h.close() }
        do { try h.seek(toOffset: start) } catch { return nil }
        let newline = UInt8(ascii: "\n")
        let usageNeedle = Data("\"usage\"".utf8), titleNeedle = Data("-title\"".utf8)
        var consumed: UInt64 = 0
        var carry = Data()                 // a line that straddles two chunks
        while true {
            let more: Bool = autoreleasepool {
                guard let chunk = try? h.read(upToCount: UsageStore.chunkSize), !chunk.isEmpty else { return false }
                var buffer = carry
                buffer.append(chunk)
                guard let lastNewline = buffer.lastIndex(of: newline) else {
                    carry = buffer        // no complete line yet (a single very long line)
                    return true
                }
                let complete = buffer[buffer.startIndex...lastNewline]
                for line in complete.split(separator: newline)
                where line.range(of: usageNeedle) != nil || line.range(of: titleNeedle) != nil {
                    ingest(Data(line), folder: folder)
                }
                consumed += UInt64(complete.count)
                carry = Data(buffer[buffer.index(after: lastNewline)...])
                return true
            }
            if !more { break }
        }
        return consumed
    }

    private static let chunkSize = 4 << 20

    private func ingest(_ line: Data, folder: String) {
        guard let obj = try? JSONSerialization.jsonObject(with: line) as? [String: Any],
              let type = obj["type"] as? String else { return }
        let session = (obj["sessionId"] as? String) ?? ""
        if type == "custom-title" || type == "ai-title" {
            let raw = (obj[type == "custom-title" ? "customTitle" : "aiTitle"] as? String) ?? ""
            let title = raw.trimmingCharacters(in: .whitespacesAndNewlines)
            if !session.isEmpty, !title.isEmpty {
                if type == "custom-title" { customTitles[session] = title } else { aiTitles[session] = title }
            }
            return
        }
        guard type == "assistant",
              let msg = obj["message"] as? [String: Any],
              let usage = msg["usage"] as? [String: Any],
              let model = msg["model"] as? String, !model.hasPrefix("<"),
              let id = (msg["id"] as? String) ?? (obj["requestId"] as? String) ?? (obj["uuid"] as? String),
              let ts = obj["timestamp"] as? String, let time = iso.date(from: ts) else { return }
        func n(_ k: String) -> Int { (usage[k] as? NSNumber)?.intValue ?? 0 }
        let tokens = TokenCounts(input: n("input_tokens"), output: n("output_tokens"),
                                 cacheWrite: n("cache_creation_input_tokens"), cacheRead: n("cache_read_input_tokens"))
        if let cwd = obj["cwd"] as? String, !cwd.isEmpty {
            if let known = folderRoot[folder] { if cwd.count < known.count { folderRoot[folder] = cwd } }
            else { folderRoot[folder] = cwd }
        }
        if var r = records[id] {
            r.tokens = r.tokens.merged(tokens)
            records[id] = r
        } else {
            records[id] = Record(time: time, folder: folder, session: session,
                                 sidechain: (obj["isSidechain"] as? Bool) ?? false, model: model, tokens: tokens)
        }
    }

    // MARK: Project names

    /// Folder -> short display name. Two folders that end the same way get their parent folder added.
    private func projectNames() -> [String: String] {
        func last(_ path: String, _ count: Int) -> String {
            let parts = path.split(separator: "/").map(String.init)
            return parts.suffix(count).joined(separator: "/")
        }
        var base: [String: String] = [:]
        for (folder, path) in folderRoot { base[folder] = last(path, 1) }
        var counts: [String: Int] = [:]
        for name in base.values { counts[name, default: 0] += 1 }
        var out: [String: String] = [:]
        for (folder, path) in folderRoot {
            let name = base[folder] ?? "Other"
            out[folder] = (counts[name] ?? 0) > 1 ? last(path, 2) : (name.isEmpty ? "Other" : name)
        }
        return out
    }

    private func displayPath(_ folder: String) -> String {
        guard let p = folderRoot[folder] else { return "" }
        let home = NSHomeDirectory()
        return p.hasPrefix(home) ? "~" + p.dropFirst(home.count) : p
    }

    // MARK: Detailed report

    /// Builds the per-project breakdown on the scanning queue and delivers it on the main queue.
    func report(_ period: UsagePeriod, completion: @escaping (UsageReport) -> Void) {
        queue.async { [weak self] in
            guard let self = self else { return }
            self.scan()                                   // pick up anything new first
            let r = self.buildReport(period)
            DispatchQueue.main.async { completion(r) }
        }
    }

    private func buildReport(_ period: UsagePeriod) -> UsageReport {
        struct SessionAcc {
            var first = Date.distantFuture, last = Date.distantPast
            var tokens = TokenCounts(), responses = 0, subFresh = 0
        }
        struct ProjectAcc {
            var tokens = TokenCounts(), responses = 0
            var sessions: [String: SessionAcc] = [:]
            var models: [String: TokenCounts] = [:]
        }
        let cal = Calendar.current
        let start = cal.date(byAdding: .day, value: -period.daysBack, to: cal.startOfDay(for: Date()))!
        var byProject: [String: ProjectAcc] = [:]
        var total = TokenCounts(), responses = 0
        for r in records.values where r.time >= start {
            total = total + r.tokens
            responses += 1
            var p = byProject[r.folder] ?? ProjectAcc()
            p.tokens = p.tokens + r.tokens
            p.responses += 1
            p.models[UsageStore.prettyModel(r.model), default: TokenCounts()] =
                p.models[UsageStore.prettyModel(r.model), default: TokenCounts()] + r.tokens
            var sa = p.sessions[r.session] ?? SessionAcc()
            sa.first = min(sa.first, r.time)
            sa.last = max(sa.last, r.time)
            sa.tokens = sa.tokens + r.tokens
            sa.responses += 1
            if r.sidechain { sa.subFresh += r.tokens.fresh }
            p.sessions[r.session] = sa
            byProject[r.folder] = p
        }
        let names = projectNames()
        let projects: [ProjectUsage] = byProject.map { folder, p in
            let sessions = p.sessions.map { id, a in
                SessionUsage(id: id, title: customTitles[id] ?? aiTitles[id], first: a.first, last: a.last,
                             tokens: a.tokens, responses: a.responses, subagentFresh: a.subFresh)
            }.sorted { $0.tokens.fresh > $1.tokens.fresh }
            let models = p.models.map { ModelUsage(name: $0.key, tokens: $0.value) }.sorted { $0.tokens.fresh > $1.tokens.fresh }
            return ProjectUsage(id: folder, name: names[folder] ?? "Other", path: displayPath(folder), tokens: p.tokens,
                                responses: p.responses, sessions: sessions, models: models)
        }.sorted { $0.tokens.fresh > $1.tokens.fresh }
        return UsageReport(period: period, start: start, total: total, responses: responses, projects: projects,
                           generated: Date())
    }

    // MARK: Summaries

    private func summarize() -> UsageSnapshot {
        let cal = Calendar.current
        let today = cal.startOfDay(for: Date())
        var snap = UsageSnapshot()
        snap.updated = Date()
        snap.responses = records.count
        var perDay: [Date: TokenCounts] = [:]
        var projects: [String: Int] = [:]
        var models: [String: Int] = [:]
        let weekStart = cal.date(byAdding: .day, value: -6, to: today)!
        let monthStart = cal.date(byAdding: .day, value: -29, to: today)!
        for r in records.values {
            let day = cal.startOfDay(for: r.time)
            perDay[day, default: TokenCounts()] = perDay[day, default: TokenCounts()] + r.tokens
            if snap.oldest == nil || r.time < snap.oldest! { snap.oldest = r.time }
            if day >= monthStart { snap.month = snap.month + r.tokens }
            if day >= weekStart {
                snap.week = snap.week + r.tokens
                projects[r.folder, default: 0] += r.tokens.fresh
                models[UsageStore.prettyModel(r.model), default: 0] += r.tokens.fresh
            }
        }
        snap.today = perDay[today] ?? TokenCounts()
        snap.days = (0..<14).reversed().map { back in
            let d = cal.date(byAdding: .day, value: -back, to: today)!
            return UsageSnapshot.Day(date: d, tokens: perDay[d] ?? TokenCounts())
        }
        let names = projectNames()
        snap.topProjects = projects.sorted { $0.value > $1.value }.prefix(3).map { (names[$0.key] ?? "Other", $0.value) }
        let modelTotal = Double(max(1, models.values.reduce(0, +)))
        snap.models = models.sorted { $0.value > $1.value }.prefix(3).map { ($0.key, Double($0.value) / modelTotal) }
        return snap
    }

    /// "claude-opus-5-5" -> "Opus 5.5", "claude-haiku-4-5-20251001" -> "Haiku 4.5"
    static func prettyModel(_ id: String) -> String {
        var parts = id.split(separator: "-").map(String.init)
        if parts.first == "claude" { parts.removeFirst() }
        if let last = parts.last, last.count == 8, Int(last) != nil { parts.removeLast() }
        guard let family = parts.first else { return id }
        let version = parts.dropFirst().filter { Int($0) != nil }.joined(separator: ".")
        return family.prefix(1).uppercased() + family.dropFirst() + (version.isEmpty ? "" : " " + version)
    }

    static func format(_ n: Int) -> String {
        let d = Double(n)
        switch d {
        case 1e9...: return String(format: d >= 1e10 ? "%.0fB" : "%.1fB", d / 1e9)
        case 1e6...: return String(format: d >= 1e7 ? "%.0fM" : "%.1fM", d / 1e6)
        case 1e3...: return String(format: d >= 1e4 ? "%.0fK" : "%.1fK", d / 1e3)
        default: return "\(n)"
        }
    }
}
